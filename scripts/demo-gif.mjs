import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { demoServer } from './demo-state.mjs';

const target = fileURLToPath(new URL('../docs/screenshots/demo.gif', import.meta.url));
const videoDir = mkdtempSync(join(tmpdir(), 'plan-live-video-'));
const { srv } = await demoServer({ seed: false });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 760 }, recordVideo: { dir: videoDir, size: { width: 1280, height: 760 } } });
const page = await ctx.newPage();
const pause = ms => page.waitForTimeout(ms);

await page.goto(`${srv.url}&theme=aurora&mode=dark`);
await page.locator('h1.title').waitFor();
await pause(2200);
const jump = async text => {
  await page.keyboard.press('Control+K');
  await pause(500);
  await page.keyboard.type(text, { delay: 90 });
  await pause(600);
  await page.keyboard.press('Enter');
};

const glide = async (locator, steps = 22) => {
  const box = await locator.boundingBox();
  await page.mouse.move(box.x + box.width * 0.5, box.y + Math.min(box.height * 0.5, 120), { steps });
};

await page.mouse.move(420, 330);
await glide(page.locator('.card').nth(2), 30);
await pause(1100);
await jump('task 2');
await pause(1200);
await page.locator('[data-task*="implement-the-endpoint"] .cb').click();
await pause(900);
await page.keyboard.press('c');
await page.locator('#composer-body').pressSequentially('Mention the idempotency key here', { delay: 35 });
await pause(300);
await page.keyboard.press('Meta+Enter');
await pause(800);
await page.locator('.apply').click();
await pause(1100);
await page.keyboard.press('t');
await pause(700);
await glide(page.locator('.card').nth(3), 26);
await pause(1500);
await page.keyboard.press('t');
await pause(700);
await glide(page.locator('.task').nth(5), 26);
await pause(1500);
await page.keyboard.press('t');
await pause(1100);
await page.keyboard.press('Control+K');
await pause(1500);
await page.keyboard.press('Escape');
await pause(600);
await page.keyboard.press('d');
await pause(1300);
await jump('architecture');
await pause(1300);
const graph = await page.locator('.arch svg.dag').boundingBox();
await page.mouse.move(graph.x + graph.width * 0.7, graph.y + graph.height * 0.5);
await page.mouse.down();
await page.mouse.move(graph.x + graph.width * 0.45, graph.y + graph.height * 0.5, { steps: 5 });
await page.mouse.move(graph.x + graph.width * 0.2, graph.y + graph.height * 0.55, { steps: 3 });
await page.mouse.up();
await pause(2200);

const video = page.video();
await ctx.close();
const webm = await video.path();
await browser.close();
await srv.close();
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', webm, '-vf', 'fps=6,scale=720:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=48:stats_mode=diff[p];[b][p]paletteuse=dither=bayer:bayer_scale=4:diff_mode=rectangle', '-loop', '0', target]);
const mp4 = process.argv[2];
if (mp4) execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', webm, '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', '27', '-preset', 'slow', '-movflags', '+faststart', '-an', mp4]);
rmSync(videoDir, { recursive: true, force: true });
console.log(target);
