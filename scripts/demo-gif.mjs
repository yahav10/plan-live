import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { demoServer } from './demo-state.mjs';

const target = fileURLToPath(new URL('../docs/screenshots/demo.gif', import.meta.url));
const videoDir = mkdtempSync(join(tmpdir(), 'plan-live-video-'));
const { srv } = await demoServer({ seed: false });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 760 }, recordVideo: { dir: videoDir, size: { width: 1280, height: 760 } } });
const page = await ctx.newPage();
const pause = ms => page.waitForTimeout(ms);

await page.goto(`${srv.url}&theme=aurora&mode=dark`);
await page.locator('h1.title').waitFor();
await pause(2200);
await page.locator('.secs a', { hasText: 'T2' }).click();
await pause(1300);
await page.locator('[data-task*="implement-the-endpoint"] .cb').click();
await pause(1000);
await page.keyboard.press('c');
await page.locator('#composer-body').pressSequentially('Mention the idempotency key here', { delay: 35 });
await pause(300);
await page.keyboard.press('Meta+Enter');
await pause(900);
await page.locator('.apply').click();
await pause(1300);
await page.keyboard.press('t');
await pause(1400);
await page.keyboard.press('t');
await pause(1400);
await page.keyboard.press('d');
await pause(1200);
await page.locator('.secs a', { hasText: 'Options' }).click();
await pause(1500);
await page.locator('[data-act=export-menu]').click();
await pause(1800);

const video = page.video();
await ctx.close();
const webm = await video.path();
await browser.close();
await srv.close();
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', webm, '-vf', 'fps=8,scale=840:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=64:stats_mode=diff[p];[b][p]paletteuse=dither=bayer:bayer_scale=3:diff_mode=rectangle', '-loop', '0', target]);
rmSync(videoDir, { recursive: true, force: true });
console.log(target);
